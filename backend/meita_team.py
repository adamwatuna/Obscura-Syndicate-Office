"""Meita's CEO-controlled cross-department meeting room.

Real multi-agent discussion: each invited AI staff member is queried separately,
then Meita receives the actual contributions and writes a cross-team synthesis.
No external tools, publishing, approvals or delegation are performed by a meeting.
"""
import json
import os
import secrets
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor, as_completed

from fastapi import HTTPException
from pydantic import BaseModel, Field
from psycopg.types.json import Jsonb

DELEGATION_SCOPES=("directors_only","all_staff")
DISCUSSION_SCOPES=("directors_only","all_staff")
MAX_MEETING_ROUNDS=3
MAX_MEETING_PEOPLE=20

class MeitaSettings(BaseModel):
    delegation_scope: str = "all_staff"
    discussion_scope: str = "all_staff"
    max_delegation_jobs: int = Field(ge=1,le=9,default=9)
    max_meeting_participants: int = Field(ge=1,le=20,default=20)
    auto_execute_internal: bool = True

class MeetingBrief(BaseModel):
    topic: str = Field(min_length=8,max_length=2500)

class MeetingFollowup(BaseModel):
    instruction: str = Field(default="",max_length=1200)

def init(db):
    db.execute("""CREATE TABLE IF NOT EXISTS meita_configuration (
        id INTEGER PRIMARY KEY CHECK (id=1),
        delegation_scope TEXT NOT NULL DEFAULT 'all_staff',
        discussion_scope TEXT NOT NULL DEFAULT 'all_staff',
        max_delegation_jobs SMALLINT NOT NULL DEFAULT 9,
        max_meeting_participants SMALLINT NOT NULL DEFAULT 20,
        auto_execute_internal BOOLEAN NOT NULL DEFAULT TRUE,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW())""")
    db.execute("ALTER TABLE meita_configuration ADD COLUMN IF NOT EXISTS auto_execute_internal BOOLEAN NOT NULL DEFAULT TRUE")
    db.execute("""INSERT INTO meita_configuration(id)
        VALUES(1) ON CONFLICT(id) DO NOTHING""")
    db.execute("""CREATE TABLE IF NOT EXISTS meita_meetings (
        id TEXT PRIMARY KEY,topic TEXT NOT NULL,
        audience TEXT NOT NULL,
        participants JSONB NOT NULL,
        status TEXT NOT NULL DEFAULT 'Open',
        round_no SMALLINT NOT NULL DEFAULT 0,
        failures JSONB NOT NULL DEFAULT '[]'::jsonb,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW())""")
    db.execute("""CREATE TABLE IF NOT EXISTS meita_meeting_messages (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        meeting_id TEXT NOT NULL REFERENCES meita_meetings(id),
        round_no SMALLINT NOT NULL,
        speaker_id TEXT NOT NULL,
        speaker_name TEXT NOT NULL,
        speaker_role TEXT NOT NULL,
        department TEXT NOT NULL,
        content TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW())""")
    db.execute("""CREATE INDEX IF NOT EXISTS meita_meeting_recent
        ON meita_meeting_messages(meeting_id,round_no,id)""")

def settings(db):
    init(db)
    return dict(db.execute("SELECT * FROM meita_configuration WHERE id=1").fetchone())

def save_settings(db,body):
    if body.delegation_scope not in DELEGATION_SCOPES:
        raise HTTPException(400,"Unknown Meita delegation scope")
    if body.discussion_scope not in DISCUSSION_SCOPES:
        raise HTTPException(400,"Unknown Meita discussion scope")
    init(db)
    db.execute("""UPDATE meita_configuration SET
        delegation_scope=%s,discussion_scope=%s,
        max_delegation_jobs=%s,max_meeting_participants=%s,
        auto_execute_internal=%s,
        updated_at=NOW() WHERE id=1""",
        (body.delegation_scope,body.discussion_scope,
         body.max_delegation_jobs,body.max_meeting_participants,
         body.auto_execute_internal))
    return {"ok":True,"settings":settings(db)}

def available_staff(db,scope):
    if scope not in DELEGATION_SCOPES:
        raise HTTPException(400,"Invalid team scope")
    query="""SELECT id,name,role,org_role,department,expertise,status
        FROM staff """
    if scope=="directors_only":
        query+="WHERE org_role='Director' "
    # Independent Internal Audit reports to the CEO and is outside Meita's
    # automatic delegation/meeting pool.
    query+=("AND org_role<>'Independent Auditor' " if "WHERE " in query
            else "WHERE org_role<>'Independent Auditor' ")
    query+="ORDER BY CASE WHEN org_role='Director' THEN 0 ELSE 1 END, department,name"
    return [dict(p) for p in db.execute(query).fetchall()]

def create_meeting(db,topic):
    init(db)
    config=settings(db)
    roster=available_staff(db,config["discussion_scope"])
    if not roster:raise HTTPException(400,"No AI staff available for a team discussion")
    if len(roster)>config["max_meeting_participants"]:
        raise HTTPException(400,
            "This team has "+str(len(roster))+" members, beyond the configured "
            "roundtable limit. Increase Meita's meeting limit (up to 20), "
            "or select Directors only in Meita Configuration.")
    # Never pass confidential staff instructions or API tokens as attendee data.
    participants=[{k:p[k] for k in
        ("id","name","role","department","org_role")}|
        {"expertise":str(p.get("expertise") or "")[:350]}
        for p in roster]
    ident="meet_"+secrets.token_hex(12)
    db.execute("""INSERT INTO meita_meetings(id,topic,audience,participants)
        VALUES(%s,%s,%s,%s)""",
        (ident,topic.strip(),config["discussion_scope"],Jsonb(participants)))
    return {"id":ident,"status":"Open","participant_count":len(participants)}

def meeting_index(db):
    init(db)
    rows=db.execute("""SELECT id,topic,audience,status,round_no,failures,participants,
        created_at,updated_at FROM meita_meetings
        ORDER BY created_at DESC LIMIT 40""").fetchall()
    return {"meetings":[{**dict(row),
            "participant_count":len(row["participants"]),
            "participants":[{k:p[k] for k in
                ("id","name","role","department","org_role")}
                for p in row["participants"]]}
            for row in rows]}

def meeting_details(db,ident):
    init(db)
    session=db.execute("SELECT * FROM meita_meetings WHERE id=%s",(ident,)).fetchone()
    if not session:raise HTTPException(404,"Team discussion not found")
    entries=db.execute("""SELECT round_no,speaker_id,speaker_name,speaker_role,
        department,content,created_at FROM meita_meeting_messages
        WHERE meeting_id=%s ORDER BY round_no,id""",(ident,)).fetchall()
    return {"meeting":dict(session),
            "messages":[dict(m) for m in entries]}

def _ai_text(data):
    answer="\n".join(item.get("text","") for block in data.get("output",[])
        if block.get("type")=="message"
        for item in block.get("content",[])
        if item.get("type")=="output_text").strip()
    if not answer:raise RuntimeError("AI did not return a text contribution")
    return answer

def _ask(instructions,input_data,max_tokens=750):
    if os.getenv("AI_ENGINE_ENABLED","false").lower()!="true":
        raise HTTPException(503,"AI engine is disabled")
    key=os.getenv("OPENAI_API_KEY","").strip()
    if not key:raise HTTPException(503,"OPENAI_API_KEY is missing")
    payload={"model":os.getenv("OPENAI_MODEL","gpt-5.4"),
             "instructions":instructions,
             "input":[{"role":"user","content":json.dumps(input_data,ensure_ascii=False)}],
             "max_output_tokens":max_tokens,"store":False}
    req=urllib.request.Request("https://api.openai.com/v1/responses",
        data=json.dumps(payload).encode(),headers={
            "Authorization":"Bearer "+key,"Content-Type":"application/json"},
        method="POST")
    try:
        with urllib.request.urlopen(req,timeout=35) as res:
            return _ai_text(json.load(res))
    except urllib.error.HTTPError as exc:
        raise HTTPException(502,"AI team discussion failed (HTTP "+str(exc.code)+")")
    except (urllib.error.URLError,TimeoutError,ValueError):
        raise HTTPException(502,"AI team discussion service unavailable")

def _speak(member,topic,prior,followup):
    prompt=(
        "You are one AI employee in Meita's INTERNAL company leadership roundtable. "
        "Speak ONLY as the named AI staff member with the supplied role and department. "
        "Offer one distinct substantive opinion, relevant operational insight, "
        "disagreement or counterargument when justified, and a practical recommendation. "
        "Acknowledge other colleagues' actual views if provided; do not invent what "
        "colleagues said or claim you talked to them outside this transcript. "
        "This is a simulated internal AI roundtable, not real employees in a conference. "
        "No publishing, sending messages, money movement, deployment or external actions. "
        "Do not make claims of real-world access or completed research. "
        "Use concise Malay-English rojak when appropriate. Max 220 words.")
    return _ask(prompt,{"team_member":member,"CEO_topic":topic,
                         "previous_meeting_notes":prior,
                         "CEO_followup_instruction":followup},max_tokens=650)

def _meita_summary(topic,contributions,prior,followup,failures):
    instructions=(
        "You are Meita, Acting COO, chairing the CEO's INTERNAL AI team roundtable. "
        "Use the ACTUAL independently generated contributions provided. "
        "Identify consensus, disagreement, blockers, decisions proposed (not approved), "
        "and clear suggested task owners. Keep source attribution to named AI contributors, "
        "do not invent statements or claim a person responded if missing. "
        "Be candid about unavailable participants. "
        "Use Malay-English rojak as appropriate. "
        "Label the proposed actions as requiring CEO approval through Delegation Desk. "
        "You cannot assign jobs, spend money, access tools, publish or authorize external "
        "actions in this meeting. Return structured headings: Executive Summary, "
        "Team Perspectives, Risks & Differences, Recommended Delegation, CEO Decisions.")
    result=_ask(instructions,{
        "topic":topic,"followup":followup,
        "previous_meeting":prior,
        "actual_staff_contributions":contributions,
        "unavailable_staff":failures},max_tokens=1500)
    return result[:6500]

def _prior_transcript(db,ident):
    rows=db.execute("""SELECT speaker_name,content FROM meita_meeting_messages
        WHERE meeting_id=%s ORDER BY round_no DESC,id DESC LIMIT 22""",
        (ident,)).fetchall()
    return [{"speaker":r["speaker_name"],"statement":r["content"][:1100]}
            for r in reversed(rows)]

def run_round(db_connect,ident,followup=""):
    # Claim first so a double click cannot spend API credits twice.
    if os.getenv("AI_ENGINE_ENABLED","false").lower()!="true" or not os.getenv("OPENAI_API_KEY","").strip():
        raise HTTPException(503,"Enable the OpenAI engine and configure the API key")
    with db_connect() as db:
        init(db)
        session=db.execute(
            "SELECT * FROM meita_meetings WHERE id=%s FOR UPDATE",(ident,)).fetchone()
        if not session:raise HTTPException(404,"Team discussion not found")
        if session["status"]=="Running":
            raise HTTPException(409,"Meita's team discussion is already running")
        if session["round_no"]>=MAX_MEETING_ROUNDS:
            raise HTTPException(409,"Maximum three discussion rounds; start a new meeting")
        participants=session["participants"]
        if not participants or len(participants)>MAX_MEETING_PEOPLE:
            raise HTTPException(400,"Invalid or oversized meeting roster")
        live={row["id"] for row in db.execute("SELECT id FROM staff").fetchall()}
        if any(p["id"] not in live for p in participants):
            raise HTTPException(409,"Team roster changed; start a new meeting")
        prior=_prior_transcript(db,ident)
        round_no=session["round_no"]+1
        topic=session["topic"]
        db.execute("""UPDATE meita_meetings SET status='Running',updated_at=NOW()
            WHERE id=%s""",(ident,))
    contributions=[]
    failed=[]
    try:
        # Calls are genuinely independent per staff persona. Parallelism limits
        # total meeting latency while respecting a 20-participant maximum.
        with ThreadPoolExecutor(max_workers=min(6,len(participants))) as pool:
            jobs={pool.submit(_speak,p,topic,prior,followup):p
                  for p in participants}
            for future in as_completed(jobs):
                member=jobs[future]
                try:
                    content=future.result()
                    contributions.append({"member":member,"statement":content[:2200]})
                except Exception:
                    failed.append({"id":member["id"],"name":member["name"],
                                   "reason":"AI response unavailable"})
        order={p["id"]:i for i,p in enumerate(participants)}
        contributions.sort(key=lambda r:order[r["member"]["id"]])
        if not contributions:
            raise HTTPException(502,"No AI team members could respond; try the meeting again")
        summary=_meita_summary(topic,contributions,prior,followup,failed)
        with db_connect() as db:
            session=db.execute(
                "SELECT round_no,status FROM meita_meetings WHERE id=%s FOR UPDATE",
                (ident,)).fetchone()
            if not session or session["status"]!="Running" or session["round_no"]!=round_no-1:
                raise HTTPException(409,"Team meeting state changed during discussion")
            for item in contributions:
                p=item["member"]
                db.execute("""INSERT INTO meita_meeting_messages
                    (meeting_id,round_no,speaker_id,speaker_name,speaker_role,
                     department,content)
                    VALUES(%s,%s,%s,%s,%s,%s,%s)""",
                    (ident,round_no,p["id"],p["name"],p["role"],
                     p["department"],item["statement"]))
            db.execute("""INSERT INTO meita_meeting_messages
                (meeting_id,round_no,speaker_id,speaker_name,speaker_role,
                 department,content)
                VALUES(%s,%s,'meita','Meita','Acting COO','Executive Office',%s)""",
                (ident,round_no,summary))
            db.execute("""UPDATE meita_meetings SET status='Open',
                round_no=%s,failures=%s,updated_at=NOW() WHERE id=%s""",
                (round_no,Jsonb(failed),ident))
            db.execute("""INSERT INTO audit(action,detail,created)
                VALUES('meita.team.roundtable',%s,EXTRACT(EPOCH FROM NOW())::bigint)""",
                (f"{ident}: round {round_no}, contributors {len(contributions)}, unavailable {len(failed)}",))
        return {"ok":True,"round_no":round_no,"contributors":len(contributions),
                "unavailable":len(failed)}
    except Exception:
        with db_connect() as db:
            db.execute("""UPDATE meita_meetings SET status='Open',updated_at=NOW()
                WHERE id=%s AND status='Running'""",(ident,))
        raise

def latest_summary(db):
    init(db)
    row=db.execute("""SELECT m.id,m.topic,msg.content
        FROM meita_meeting_messages msg
        JOIN meita_meetings m ON m.id=msg.meeting_id
        WHERE msg.speaker_id='meita'
        ORDER BY msg.id DESC LIMIT 1""").fetchone()
    if not row:return None
    return {"meeting_id":row["id"],"topic":row["topic"],
            "summary":row["content"][:2200]}

def proposal_brief_from_meeting(db,ident):
    item=meeting_details(db,ident)
    summaries=[m["content"] for m in item["messages"] if m["speaker_id"]=="meita"]
    if not summaries:
        raise HTTPException(409,"Run at least one round before requesting delegation")
    latest=summaries[-1]
    # Existing COO Delegation Desk accepts max 2,500 chars for a CEO-reviewed plan.
    return ("Delegate the internally proposed responsibilities from our Meita team "
            "roundtable. Topic: "+item["meeting"]["topic"][:400]+"\n"
            "Last Meita synthesis:\n"+latest[:1700]+
            "\nDraft assigned work only; CEO approval is required.")[:2450]
