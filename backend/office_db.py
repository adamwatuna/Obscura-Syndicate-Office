"""PostgreSQL primary store and non-destructive import of any accessible legacy SQLite."""
import logging
import os
import sqlite3
from pathlib import Path

import psycopg
from psycopg.rows import dict_row
from psycopg.types.json import Jsonb

logger = logging.getLogger("office.storage")
ROOT = Path(__file__).resolve().parent.parent
LEGACY_TABLES = ("staff", "tasks", "lessons", "meita_messages", "audit")

def connect():
    url = os.environ.get("DATABASE_URL", "").strip()
    if not url:
        raise RuntimeError("DATABASE_URL is required for office persistence")
    return psycopg.connect(url, row_factory=dict_row, connect_timeout=8)

def ensure_schema(db):
    db.execute("""CREATE TABLE IF NOT EXISTS staff (
        id TEXT PRIMARY KEY, name TEXT NOT NULL, role TEXT NOT NULL,
        department TEXT NOT NULL, expertise TEXT NOT NULL DEFAULT '',
        tools TEXT NOT NULL DEFAULT '',
        autonomy TEXT NOT NULL DEFAULT 'Approval required',
        status TEXT NOT NULL DEFAULT 'Available')""")
    db.execute("""CREATE TABLE IF NOT EXISTS tasks (
        id TEXT PRIMARY KEY, title TEXT NOT NULL,
        assignee TEXT NOT NULL DEFAULT '',
        status TEXT NOT NULL DEFAULT 'To do',
        created BIGINT NOT NULL)""")
    db.execute("""CREATE TABLE IF NOT EXISTS lessons (
        id TEXT PRIMARY KEY, title TEXT NOT NULL,
        kind TEXT NOT NULL, source TEXT NOT NULL,
        assigned TEXT NOT NULL DEFAULT '',
        status TEXT NOT NULL DEFAULT 'Pending review',
        created BIGINT NOT NULL)""")
    db.execute("""CREATE TABLE IF NOT EXISTS meita_messages (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        role TEXT NOT NULL, content TEXT NOT NULL,
        created BIGINT NOT NULL, legacy_id BIGINT UNIQUE)""")
    db.execute("""CREATE TABLE IF NOT EXISTS audit (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        action TEXT NOT NULL, detail TEXT NOT NULL,
        created BIGINT NOT NULL, legacy_id BIGINT UNIQUE)""")
    db.execute("""CREATE TABLE IF NOT EXISTS office_import_log (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        source_state TEXT NOT NULL, source_rows JSONB NOT NULL,
        copied_rows JSONB NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW())""")

def _copy_table(db, old, name):
    source_count = copied_count = 0
    if name in ("staff", "tasks", "lessons"):
        fields = {
            "staff": ("id","name","role","department","expertise","tools","autonomy","status"),
            "tasks": ("id","title","assignee","status","created"),
            "lessons": ("id","title","kind","source","assigned","status","created"),
        }[name]
        columns = ",".join(fields)
        placeholders = ",".join(["%s"] * len(fields))
        query = f"INSERT INTO {name} ({columns}) VALUES ({placeholders}) ON CONFLICT (id) DO NOTHING"
        for row in old.execute(f"SELECT {columns} FROM {name}"):
            source_count += 1
            result = db.execute(query,tuple(row[field] for field in fields))
            copied_count += result.rowcount
    else:
        fields=("role","content","created") if name=="meita_messages" else ("action","detail","created")
        columns=",".join(fields)+",legacy_id"
        placeholders=",".join(["%s"] * (len(fields)+1))
        query=(f"INSERT INTO {name} ({columns}) VALUES ({placeholders}) "
               "ON CONFLICT (legacy_id) DO NOTHING")
        for row in old.execute(f"SELECT id,{','.join(fields)} FROM {name} ORDER BY id"):
            source_count += 1
            result=db.execute(query,tuple(row[field] for field in fields)+(row["id"],))
            copied_count += result.rowcount
    return source_count,copied_count

def import_legacy(db, path):
    counts={name:0 for name in LEGACY_TABLES}
    copied=counts.copy()
    if not path.is_file():
        return "legacy_file_not_found", counts, copied
    # Open the original read-only. Never change or remove the SQLite file.
    with sqlite3.connect(path.resolve().as_uri()+"?mode=ro", uri=True, timeout=8) as old:
        old.row_factory=sqlite3.Row
        old.execute("BEGIN")
        available={r["name"] for r in old.execute(
            "SELECT name FROM sqlite_master WHERE type='table'")}
        for name in LEGACY_TABLES:
            if name in available:
                counts[name],copied[name]=_copy_table(db,old,name)
    return "legacy_file_read",counts,copied

def bootstrap(legacy_path=None):
    path=Path(legacy_path) if legacy_path is not None else Path(
        os.environ.get("DATABASE_PATH", str(ROOT/"office.sqlite3")))
    with connect() as db:
        # Prevent concurrent schema/import races across multiple startup workers.
        db.execute("SELECT pg_advisory_xact_lock(815024, 12026)")
        ensure_schema(db)
        state,counts,copied=import_legacy(db,path)
        db.execute("""INSERT INTO office_import_log
            (source_state,source_rows,copied_rows) VALUES (%s,%s,%s)""",
            (state,Jsonb(counts),Jsonb(copied)))
    logger.info("Office PostgreSQL ready. Legacy import state=%s source=%s copied=%s",
                state,counts,copied)
    return {"state":state,"source_rows":counts,"copied_rows":copied}

def status():
    with connect() as db:
        latest=db.execute("""SELECT source_state,source_rows,copied_rows,created_at
            FROM office_import_log ORDER BY id DESC LIMIT 1""").fetchone()
        counts={name:db.execute(f"SELECT COUNT(*) AS n FROM {name}").fetchone()["n"]
                for name in LEGACY_TABLES}
    return {"primary_database":"PostgreSQL","records":counts,"legacy_import":latest}
